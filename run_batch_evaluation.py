"""
PolicyPal-AI — Real 75-Run Batch Evaluation
============================================
Executes all 25 evaluation questions through all 3 Ollama models.
Every answer is generated by the actual model — no cache, no fabrication.
Retrieval is performed ONCE per question; same context given to all 3 models.
Results saved to evaluation_results_live.json and evaluation_results_live.csv.

Usage:
    venv/bin/python run_batch_evaluation.py
"""

import json
import math
import re
import time
import csv
from datetime import datetime, timezone
from pathlib import Path

import requests

# ─── Config ────────────────────────────────────────────────────────────────
BASE_URL    = "http://localhost:8080"   # running PolicyPal app
MODELS      = ["codellama:latest", "qwen2.5:0.5b", "tinyllama:1.1b"]
DATASET     = "evaluation_dataset.json"
OUT_JSON    = "evaluation_results_live.json"
OUT_CSV     = "evaluation_results_live.csv"
TIMEOUT_S   = 300  # per model call
PAUSE_S     = 2    # between questions to let Ollama breathe

# ─── Scoring (same logic as run_evaluation.py) ─────────────────────────────
STOP = {"with","that","this","from","have","been","they","will","which","when",
        "were","also","into","than","such","more","their","under","shall",
        "person","where","section","made","upon","like","both","each","must"}

def kw_overlap(response: str, ground_truth: str) -> float:
    def tok(t):
        words = re.findall(r"[a-z]{4,}", t.lower())
        return set(w for w in words if w not in STOP)
    gt = tok(ground_truth)
    if not gt: return 0.0
    return round(len(gt & tok(response)) / len(gt), 4)


def score_correctness(response: str, q_meta: dict) -> dict:
    resp_lower = (response or "").lower().strip()
    if not q_meta.get("kb_supported", True):
        not_found = ["not found","not available","not in the","cannot find",
                     "could not find","no information","not provided",
                     "not mentioned","outside","not covered","not contain",
                     "does not contain","i could not","not part of",
                     "not included","not present","no specific"]
        is_refusal = any(p in resp_lower for p in not_found)
        gives_num  = bool(re.search(r'\b(0|5|10|12|15|18|20|28)\s*%', resp_lower))
        gives_slab = bool(re.search(r'\b(lakh|tax slab|income tax rate|percent)', resp_lower))
        if is_refusal and not gives_num:
            return {"correctness_score": 2, "hallucination": False,
                    "method": "refusal_check",
                    "details": "Correctly refused out-of-scope question"}
        elif gives_num or gives_slab:
            return {"correctness_score": 0, "hallucination": True,
                    "method": "refusal_check",
                    "details": "Hallucinated specific value for out-of-scope question"}
        else:
            return {"correctness_score": 1, "hallucination": False,
                    "method": "refusal_check",
                    "details": "Partial refusal — vague, no fabricated value"}
    else:
        gt      = q_meta.get("ground_truth", "")
        overlap = kw_overlap(response, gt) if gt else 0.0
        score   = 2 if overlap >= 0.40 else 1 if overlap >= 0.20 else 0
        return {"correctness_score": score, "hallucination": False,
                "method": "keyword_overlap",
                "keyword_overlap": overlap,
                "details": f"Keyword overlap: {overlap:.4f}"}


def score_relevance(response: str, question: str) -> float:
    def tok(t): return set(re.findall(r"[a-z]{4,}", t.lower()))
    q = tok(question); r = tok(response)
    return round(len(q & r) / len(q), 4) if q else 0.0


# ─── Load dataset ────────────────────────────────────────────────────────────
with open(DATASET, encoding="utf-8") as f:
    questions = json.load(f)["questions"]

print(f"Loaded {len(questions)} questions from {DATASET}")
print(f"Models: {MODELS}")
print(f"Total planned runs: {len(questions) * len(MODELS)}")
print()

# ─── Main evaluation loop ────────────────────────────────────────────────────
results = []
total   = len(questions) * len(MODELS)
done    = 0
errors  = 0

for q in questions:
    # Call /api/compare-models — one call, retrieval once, all 3 models
    url = (f"{BASE_URL}/api/compare-models"
           f"?question={requests.utils.quote(q['question'])}"
           f"&question_id={q['id']}")

    print(f"{'─'*65}")
    print(f"[{q['id']}] {q['question'][:60]}...")
    print(f"  KB={q['kb_supported']} | Trap={q.get('tests_hallucination',False)} | {q['category']} / {q['difficulty']}")

    api_data = None
    api_err  = None
    t_call   = time.time()
    try:
        resp = requests.post(url, timeout=TIMEOUT_S * len(MODELS) + 60)
        resp.raise_for_status()
        api_data = resp.json()
    except Exception as e:
        api_err = str(e)
        print(f"  API call failed: {api_err}")

    # Build one record per model
    for model in MODELS:
        done += 1
        print(f"  [{done:02d}/{total}] {model}", end="  ", flush=True)

        if api_err or api_data is None:
            errors += 1
            results.append({
                "model": model, "question_id": q["id"],
                "question": q["question"],
                "category": q["category"], "difficulty": q["difficulty"],
                "question_type": q["type"],
                "kb_supported": q["kb_supported"],
                "expected_source": q["expected_source"],
                "ground_truth": q.get("ground_truth",""),
                "actual_answer": None,
                "source": "live",
                "latency_ms": None, "llm_latency_ms": None,
                "retrieval_ms": None,
                "retrieved_chunks": [],
                "total_chunks_searched": None,
                "correctness_score": None, "hallucination": None,
                "relevance_score": None, "retrieval_quality_score": None,
                "scoring_method": None, "keyword_overlap": None,
                "is_trap": q.get("tests_hallucination", False),
                "kb_match": None,
                "error": api_err or "No API response",
            })
            print(f"ERROR: {api_err}")
            continue

        model_result = next(
            (m for m in api_data.get("models", []) if m["model"] == model), None
        )

        if model_result is None:
            errors += 1
            results.append({
                "model": model, "question_id": q["id"],
                "question": q["question"],
                "category": q["category"], "difficulty": q["difficulty"],
                "question_type": q["type"],
                "kb_supported": q["kb_supported"],
                "expected_source": q["expected_source"],
                "ground_truth": q.get("ground_truth",""),
                "actual_answer": None,
                "source": "live",
                "latency_ms": None, "llm_latency_ms": None,
                "retrieval_ms": api_data.get("retrieval_ms"),
                "retrieved_chunks": api_data.get("shared_retrieval",[]),
                "total_chunks_searched": None,
                "correctness_score": None, "hallucination": None,
                "relevance_score": None, "retrieval_quality_score": None,
                "scoring_method": None, "keyword_overlap": None,
                "is_trap": api_data.get("is_trap", False),
                "kb_match": None,
                "error": f"Model {model} not found in API response",
            })
            print(f"ERROR: model not in response")
            continue

        # Real answer from the model
        err     = model_result.get("error")
        answer  = model_result.get("answer") or ""
        is_trap = model_result.get("is_trap", False) or api_data.get("is_trap", False)

        # Real scoring
        scoring = score_correctness(answer, q)
        rel     = score_relevance(answer, q["question"])
        ret_q   = model_result.get("retrieval_quality_score")

        if err:
            errors += 1
            # Error: keep real latency if available
            results.append({
                "model": model, "question_id": q["id"],
                "question": q["question"],
                "category": q["category"], "difficulty": q["difficulty"],
                "question_type": q["type"],
                "kb_supported": q["kb_supported"],
                "expected_source": q["expected_source"],
                "ground_truth": q.get("ground_truth",""),
                "actual_answer": None,
                "source": "live",
                "latency_ms": model_result.get("latency_ms"),
                "llm_latency_ms": model_result.get("llm_latency_ms"),
                "retrieval_ms": api_data.get("retrieval_ms"),
                "retrieved_chunks": model_result.get("retrieved_chunks", []),
                "total_chunks_searched": model_result.get("total_chunks_searched"),
                "correctness_score": None, "hallucination": None,
                "relevance_score": None, "retrieval_quality_score": None,
                "scoring_method": None, "keyword_overlap": None,
                "is_trap": is_trap,
                "kb_match": model_result.get("kb_match"),
                "error": err,
            })
            print(f"ERROR: {err[:50]}")
        else:
            sc = scoring["correctness_score"]
            print(f"✓  lat={model_result.get('latency_ms')}ms  score={sc}  "
                  f"ans={answer[:50]}…")
            results.append({
                "model": model, "question_id": q["id"],
                "question": q["question"],
                "category": q["category"], "difficulty": q["difficulty"],
                "question_type": q["type"],
                "kb_supported": q["kb_supported"],
                "expected_source": q["expected_source"],
                "ground_truth": q.get("ground_truth",""),
                "actual_answer": answer,
                "source": "live",
                "latency_ms": model_result.get("latency_ms"),
                "llm_latency_ms": model_result.get("llm_latency_ms"),
                "retrieval_ms": api_data.get("retrieval_ms"),
                "retrieved_chunks": model_result.get("retrieved_chunks", []),
                "total_chunks_searched": model_result.get("total_chunks_searched"),
                "correctness_score": scoring["correctness_score"],
                "hallucination": scoring.get("hallucination", False),
                "relevance_score": rel,
                "retrieval_quality_score": ret_q,
                "scoring_method": scoring.get("method"),
                "keyword_overlap": scoring.get("keyword_overlap"),
                "is_trap": is_trap,
                "kb_match": model_result.get("kb_match"),
                "error": None,
            })

    time.sleep(PAUSE_S)

# ─── Save JSON ────────────────────────────────────────────────────────────────
output = {
    "metadata": {
        "evaluation_type": "REAL LIVE EXECUTION — no cache, no fabrication",
        "run_at": datetime.now(timezone.utc).isoformat(),
        "models": MODELS,
        "total_questions": len(questions),
        "total_calls": len(results),
        "errors": errors,
        "dataset_file": DATASET,
        "source": "live — all answers generated by actual Ollama model execution",
        "scoring": {
            "correctness": "0=wrong/hallucinated, 1=partial, 2=correct (KB: keyword overlap ≥0.40→2, ≥0.20→1. Trap: refusal→2, fabricated→0)",
            "relevance": "Keyword overlap (0.0–1.0) between question tokens and response tokens",
            "hallucination": "True if model fabricated a specific value for an out-of-scope question",
        },
        "token_usage": "unavailable — Ollama /api/generate does not return token counts",
        "cpu_usage":   "unavailable — not measured at request level",
        "memory_mb":   "unavailable — not measured at request level",
    },
    "results": results,
}

with open(OUT_JSON, "w", encoding="utf-8") as f:
    json.dump(output, f, indent=2, ensure_ascii=False)

print(f"\n✓ Saved {len(results)} results → {OUT_JSON}")

# ─── Save CSV ─────────────────────────────────────────────────────────────────
CSV_FIELDS = [
    "model","question_id","question","category","difficulty","question_type",
    "kb_supported","expected_source","is_trap","kb_match",
    "latency_ms","llm_latency_ms","retrieval_ms","total_chunks_searched",
    "correctness_score","hallucination","relevance_score","retrieval_quality_score",
    "scoring_method","keyword_overlap","source","error",
    "actual_answer_preview",
]

with open(OUT_CSV, "w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=CSV_FIELDS, extrasaction="ignore")
    w.writeheader()
    for r in results:
        row = {k: r.get(k,"") for k in CSV_FIELDS}
        row["actual_answer_preview"] = (r.get("actual_answer") or "")[:200].replace("\n"," ")
        w.writerow(row)

print(f"✓ Saved CSV → {OUT_CSV}")

# ─── Per-model aggregate summary ──────────────────────────────────────────────
print("\n" + "="*65)
print("  REAL EVALUATION SUMMARY")
print("="*65)

from collections import defaultdict
by_model = defaultdict(list)
for r in results:
    by_model[r["model"]].append(r)

def avg(lst): return round(sum(lst)/len(lst), 3) if lst else None

for model in MODELS:
    rs   = by_model[model]
    ok   = [r for r in rs if r.get("error") is None and r.get("actual_answer")]
    errs = [r for r in rs if r.get("error")]

    n = len(ok)
    if n == 0:
        print(f"\n  {model}: 0 valid / {len(rs)} total — ALL FAILED")
        continue

    scores   = [r["correctness_score"] for r in ok]
    lats     = [r["latency_ms"]        for r in ok if r.get("latency_ms")]
    rels     = [r["relevance_score"]   for r in ok if r.get("relevance_score") is not None]
    halls    = [r for r in ok if r.get("hallucination")]
    ret_hits = [r for r in ok if r.get("retrieval_quality_score") == 1]

    # Accuracy: correct (score=2) / total valid questions
    correct_count = sum(1 for s in scores if s == 2)
    accuracy_pct  = round(correct_count / len(rs) * 100, 1)   # over all 25

    dist = {0: scores.count(0), 1: scores.count(1), 2: scores.count(2)}

    print(f"\n  {model}")
    print(f"    Real executions      : {len(rs)} / 25")
    print(f"    Valid (non-error)    : {n}")
    print(f"    Errors               : {len(errs)}")
    print(f"    Correct (score=2)    : {correct_count}")
    print(f"    Accuracy             : {correct_count}/{len(rs)} = {accuracy_pct}%")
    print(f"    Avg correctness      : {avg(scores)} / 2.0")
    print(f"    Avg relevance        : {avg(rels)} / 1.0")
    print(f"    Hallucinations       : {len(halls)} ({round(len(halls)/n*100,1)}%)")
    print(f"    Retrieval hit rate   : {round(len(ret_hits)/len([r for r in ok if r.get('retrieval_quality_score') is not None])*100,1) if [r for r in ok if r.get('retrieval_quality_score') is not None] else 'N/A'}%")
    print(f"    Avg latency          : {avg(lats)} ms")
    print(f"    Score dist (0/1/2)   : {dist[0]}/{dist[1]}/{dist[2]}")
    print(f"    Token/CPU/Memory     : Not measured")

print("\n" + "="*65)
print(f"  TOTAL: {len(results)} records  |  errors: {errors}")
print(f"  Files: {OUT_JSON}  |  {OUT_CSV}")
print("="*65)
